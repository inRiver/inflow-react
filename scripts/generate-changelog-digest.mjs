import { readFile, writeFile } from 'node:fs/promises';

const changelogPath = new URL('../CHANGELOG.md', import.meta.url);
const startMarker = '<!-- consumer-digest:start -->';
const endMarker = '<!-- consumer-digest:end -->';

function generateDigest(source) {
  const releases = [];
  let release;
  let section;
  let droppingBullet = false;
  let bulletsKept = 0;
  let bulletsDropped = 0;

  for (const line of source.split(/\r?\n/)) {
    if (/^## \[/.test(line)) {
      release = { heading: `#${line}`, sections: [] };
      releases.push(release);
      section = { heading: null, lines: [], bullets: 0 };
      release.sections.push(section);
      droppingBullet = false;
    } else if (release && line.startsWith('### ')) {
      section = { heading: `#${line}`, lines: [], bullets: 0 };
      release.sections.push(section);
      droppingBullet = false;
    } else if (section) {
      // Never copy HTML comments (markdownlint pragmas etc.) into the digest.
      if (line.trim().startsWith('<!--')) continue;

      if (line.startsWith('- ')) {
        droppingBullet = /^- (?:\*\*)?Showcase-only:/i.test(line);
        if (droppingBullet) bulletsDropped += 1;
      } else if (line.trim() && !/^\s/.test(line)) {
        droppingBullet = false;
      }

      if (droppingBullet) continue;

      if (/^\s*- /.test(line)) {
        section.bullets += 1;
        bulletsKept += 1;
      }
      section.lines.push(line.replace(/ \(library-facing\)(\.)?$/, '$1'));
    }
  }

  if (releases.length === 0) {
    throw new Error('No release headers found in CHANGELOG.md; file was not changed.');
  }

  const included = releases.filter(item => item.sections.some(part => part.bullets > 0));
  const blocks = included.map(item => {
    const sections = item.sections.filter(part => part.bullets > 0).map(part => {
      const lines = [...part.lines];
      while (lines.length && !lines[0].trim()) lines.shift();
      while (lines.length && !lines.at(-1).trim()) lines.pop();
      return [...(part.heading ? [part.heading] : []), ...lines].join('\n');
    });
    return [item.heading, ...sections].join('\n\n');
  });

  return {
    content: [
      '_Auto-generated by `npm run changelog:digest` from the entries below \u2014 showcase-only changes omitted. Do not edit by hand._',
      ...blocks,
    ].join('\n\n'),
    releasesIncluded: included.length,
    bulletsKept,
    bulletsDropped,
  };
}

try {
  const original = await readFile(changelogPath, 'utf8');
  const newline = original.includes('\r\n') ? '\r\n' : '\n';
  const start = original.indexOf(startMarker);
  const end = original.indexOf(endMarker);
  const hasMarkers = start !== -1 || end !== -1;

  if (hasMarkers && (start === -1 || end < start + startMarker.length)) {
    throw new Error('Invalid consumer digest markers; file was not changed.');
  }

  // Exclude the old digest so generated headings can never become source entries.
  const source = hasMarkers
    ? original.slice(0, start) + original.slice(end + endMarker.length)
    : original;
  const digest = generateDigest(source);
  const content = digest.content.replace(/\n/g, newline);
  let updated;

  if (hasMarkers) {
    updated = original.slice(0, start + startMarker.length)
      + newline + content + newline
      + original.slice(end);
  } else {
    const insertion = original.search(/^## /m);
    const intro = original.slice(0, insertion).replace(/(?:\r?\n)+$/, '');
    const block = ['## For Library Consumers', '', startMarker, content, endMarker].join(newline);
    updated = intro + newline + newline + block + newline + newline + original.slice(insertion);
  }

  if (updated !== original) await writeFile(changelogPath, updated, 'utf8');
  console.log(`Consumer digest: ${digest.releasesIncluded} releases included, ${digest.bulletsKept} bullets kept, ${digest.bulletsDropped} bullets dropped.`);
} catch (error) {
  console.error(error instanceof Error ? error.message : String(error));
  process.exitCode = 1;
}
